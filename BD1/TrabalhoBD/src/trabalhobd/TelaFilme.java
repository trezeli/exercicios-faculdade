    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String nome = txtNome.getText().trim();
        if (nome.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe o nome do filme.",
                "Atenção", JOptionPane.WARNING_MESSAGE);
            txtNome.requestFocus();
            return;
        }
        Item cor = (Item) cmbCor.getSelectedItem();
        Item genero = (Item) cmbGenero.getSelectedItem();

        Filme f = new Filme();
        f.setNomFilme(nome);
        f.setCodCor(cor.getCodigo());
        f.setCodGenero(Integer.parseInt(genero.getCodigo()));

        try {
            if (selecionado == null) {
                bd.incluir(f);
            } else {
                f.setCodFilme(selecionado.getCodFilme());
                bd.alterar(f);
            }
            atualizarLista();
            limparCampos();
            JOptionPane.showMessageDialog(this, "Filme salvo com sucesso.");
        } catch (SQLException e) {
            mostrarErro("Não foi possível salvar o filme.", e);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

