    private void configurarTabela() {
    tblFilmes.setModel(new DefaultTableModel(new Object[]{"Nome", "Cor", "Gênero"}, 0) {
        @Override
        public boolean isCellEditable(int linha, int coluna) {
            return false;
        }
    });
    tblFilmes.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);

    tblFilmes.getSelectionModel().addListSelectionListener(e -> {
        if (e.getValueIsAdjusting()) {
            return;
        }
        int linha = tblFilmes.getSelectedRow();
        if (linha >= 0) {
            selecionado = exibidos.get(linha);
            txtNome.setText(selecionado.getNomFilme());
            selecionarItem(cmbCor, selecionado.getCodCor());
            selecionarItem(cmbGenero, String.valueOf(selecionado.getCodGenero()));
        }
    });
    }
    
    private void carregarCombos() {
    try {
        cmbCor.removeAllItems();
        for (Item i : bd.listarCores()) {
            cmbCor.addItem(i);
        }
        cmbGenero.removeAllItems();
        for (Item i : bd.listarGeneros()) {
            cmbGenero.addItem(i);
        }
    } catch (SQLException e) {
        mostrarErro("Não foi possível carregar cores e gêneros.", e);
    }
}

    private void carregarFilmes() {
        try {
            todos = bd.listar();
            exibidos = new ArrayList<>(todos);
            preencherTabela();
        } catch (SQLException e) {
            mostrarErro("Não foi possível carregar os filmes.", e);
        }
    }

    private void preencherTabela() {
        DefaultTableModel modelo = (DefaultTableModel) tblFilmes.getModel();
        modelo.setRowCount(0);
        for (Filme f : exibidos) {
            modelo.addRow(new Object[]{f.getNomFilme(), f.getNomCor(), f.getNomGenero()});
        }
    }

    private void selecionarItem(JComboBox<Item> combo, String codigo) {
        for (int i = 0; i < combo.getItemCount(); i++) {
            if (combo.getItemAt(i).getCodigo().equals(codigo)) {
                combo.setSelectedIndex(i);
                return;
            }
        }
    }

    private void mostrarErro(String mensagem, SQLException e) {
        JOptionPane.showMessageDialog(this, mensagem, "Erro", JOptionPane.ERROR_MESSAGE);
        e.printStackTrace();
    }
    
    private void limparCampos() {
    selecionado = null;
    tblFilmes.clearSelection();
    txtNome.setText("");
    if (cmbCor.getItemCount() > 0) cmbCor.setSelectedIndex(0);
    if (cmbGenero.getItemCount() > 0) cmbGenero.setSelectedIndex(0);
    txtNome.requestFocus();
}

    private void atualizarLista() {
        carregarFilmes();
        btnBuscarActionPerformed(null);
    }

    private String mensagemExclusao(SQLException e) {
        if ("23503".equals(e.getSQLState())) {
            return "Este filme possui fitas cadastradas e não pode ser excluído.";
        }
        return "Não foi possível excluir o filme.";
    }
