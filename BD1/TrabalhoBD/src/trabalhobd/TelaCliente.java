    private void btnAddDependenteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddDependenteActionPerformed
        String nome = txtNomeDep.getText().trim();
        if (nome.isEmpty()) {
            aviso("Informe o nome do dependente.");
            txtNomeDep.requestFocus();
            return;
        }
        Item sit = (Item) cmbSituacaoDep.getSelectedItem();

        Cliente d = new Cliente();           // codCliente = 0 -> dependente novo
        d.setNomCliente(nome);
        d.setSitCliente(Integer.parseInt(sit.getCodigo()));
        dependentes.add(d);

        preencherDependentes();
        txtNomeDep.setText("");
        txtNomeDep.requestFocus();
    }//GEN-LAST:event_btnAddDependenteActionPerformed

