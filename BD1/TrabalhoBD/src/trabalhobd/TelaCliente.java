    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String texto = txtBusca.getText().trim();
        if (texto.length() < 3) {
            aviso("Digite pelo menos 3 letras para buscar.");
            return;
        }
        try {
            titulares = bd.buscarTitulares(texto);
            preencherTitulares();
            if (titulares.isEmpty()) {
                aviso("Nenhum titular encontrado.");
            }
        } catch (SQLException e) {
            mostrarErro("Não foi possível buscar os titulares.", e);
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnRemoverDependenteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoverDependenteActionPerformed
        int linha = tblDependentes.getSelectedRow();
        if (linha < 0) {
            aviso("Selecione um dependente na tabela.");
            return;
        }
        Cliente d = dependentes.remove(linha);
        if (d.getCodCliente() != 0) {
            removidos.add(d.getCodCliente());   // já existe no banco: apaga no Salvar
        }
        preencherDependentes();
    }//GEN-LAST:event_btnRemoverDependenteActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String nome = txtNome.getText().trim();
        String uf = txtUf.getText().trim().toUpperCase();
        if (nome.isEmpty()) {
            aviso("Informe o nome do titular.");
            txtNome.requestFocus();
            return;
        }
        if (uf.length() != 2) {
            aviso("A UF deve ter 2 letras.");
            txtUf.requestFocus();
            return;
        }

        Cliente t = new Cliente();
        t.setNomCliente(nome);
        t.setRuaCliente(txtRua.getText().trim());
        t.setBaiCliente(txtBairro.getText().trim());
        t.setCidCliente(txtCidade.getText().trim());
        t.setUfCliente(uf);
        t.setSitCliente(Integer.parseInt(((Item) cmbSituacao.getSelectedItem()).getCodigo()));

        // dependente usa o mesmo endereço do titular
        for (Cliente d : dependentes) {
            d.setRuaCliente(t.getRuaCliente());
            d.setBaiCliente(t.getBaiCliente());
            d.setCidCliente(t.getCidCliente());
            d.setUfCliente(t.getUfCliente());
        }

        try {
            if (selecionado == null) {
                bd.incluir(t, dependentes);
            } else {
                t.setCodCliente(selecionado.getCodCliente());
                bd.alterar(t, dependentes, removidos);
            }
            limparTudo();
            titulares = new ArrayList<>();
            preencherTitulares();
            JOptionPane.showMessageDialog(this, "Cliente salvo com sucesso.");
        } catch (SQLException e) {
            mostrarErro("Não foi possível salvar o cliente.", e);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (selecionado == null) {
            aviso("Selecione um titular na tabela.");
            return;
        }
        int r = JOptionPane.showConfirmDialog(this,
                "Excluir \"" + selecionado.getNomCliente() + "\" e todos os seus dependentes?",
                "Confirmar exclusão", JOptionPane.YES_NO_OPTION);
        if (r != JOptionPane.YES_OPTION) return;

        try {
            bd.excluir(selecionado.getCodCliente());
            limparTudo();
            titulares = new ArrayList<>();
            preencherTitulares();
        } catch (SQLException e) {
            String msg = "23503".equals(e.getSQLState())
                    ? "Este cliente possui locações e não pode ser excluído."
                    : "Não foi possível excluir o cliente.";
            JOptionPane.showMessageDialog(this, msg, "Erro", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

