    private void configurarTabelas() {
        tblTitulares.setModel(new DefaultTableModel(new Object[]{"Nome", "Cidade"}, 0) {
            @Override
            public boolean isCellEditable(int l, int c) {
                return false;
            }
        });
        tblTitulares.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);

        tblDependentes.setModel(new DefaultTableModel(new Object[]{"Nome", "Situação"}, 0) {
            @Override
            public boolean isCellEditable(int l, int c) {
                return false;
            }
        });
        tblDependentes.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);

        tblTitulares.getSelectionModel().addListSelectionListener(e -> {
            if (e.getValueIsAdjusting()) {
                return;
            }
            int linha = tblTitulares.getSelectedRow();
            if (linha >= 0) {
                selecionado = titulares.get(linha);
                txtNome.setText(selecionado.getNomCliente());
                txtRua.setText(selecionado.getRuaCliente());
                txtBairro.setText(selecionado.getBaiCliente());
                txtCidade.setText(selecionado.getCidCliente());
                txtUf.setText(selecionado.getUfCliente());
                selecionarSituacao(cmbSituacao, selecionado.getSitCliente());
                carregarDependentes();
            }
        });
    }

    private void carregarSituacoes() {
        try {
            List<Item> lista = bd.listarSituacoes();   // 1 consulta só
            cmbSituacao.removeAllItems();
            cmbSituacaoDep.removeAllItems();
            for (Item i : lista) {
                cmbSituacao.addItem(i);
                cmbSituacaoDep.addItem(i);
            }
        } catch (SQLException e) {
            mostrarErro("Não foi possível carregar as situações.", e);
        }
    }

    private void selecionarSituacao(javax.swing.JComboBox<Item> combo, int codigo) {
        for (int i = 0; i < combo.getItemCount(); i++) {
            if (combo.getItemAt(i).getCodigo().equals(String.valueOf(codigo))) {
                combo.setSelectedIndex(i);
                return;
            }
        }
    }

    private String textoSituacao(int codigo) {
        for (int i = 0; i < cmbSituacao.getItemCount(); i++) {
            if (cmbSituacao.getItemAt(i).getCodigo().equals(String.valueOf(codigo))) {
                return cmbSituacao.getItemAt(i).getNome();
            }
        }
        return String.valueOf(codigo);
    }

    private void carregarDependentes() {
        try {
            dependentes = bd.listarDependentes(selecionado.getCodCliente());
            removidos = new ArrayList<>();
            preencherDependentes();
        } catch (SQLException e) {
            mostrarErro("Não foi possível carregar os dependentes.", e);
        }
    }

    private void preencherDependentes() {
        DefaultTableModel m = (DefaultTableModel) tblDependentes.getModel();
        m.setRowCount(0);
        for (Cliente d : dependentes) {
            m.addRow(new Object[]{d.getNomCliente(), textoSituacao(d.getSitCliente())});
        }
    }

    private void preencherTitulares() {
        DefaultTableModel m = (DefaultTableModel) tblTitulares.getModel();
        m.setRowCount(0);
        for (Cliente c : titulares) {
            m.addRow(new Object[]{c.getNomCliente(), c.getCidCliente()});
        }
    }

    private void limparTudo() {
        selecionado = null;
        dependentes = new ArrayList<>();
        removidos = new ArrayList<>();
        txtNome.setText("");
        txtRua.setText("");
        txtBairro.setText("");
        txtCidade.setText("");
        txtUf.setText("");
        txtNomeDep.setText("");
        if (cmbSituacao.getItemCount() > 0) {
            cmbSituacao.setSelectedIndex(0);
        }
        if (cmbSituacaoDep.getItemCount() > 0) {
            cmbSituacaoDep.setSelectedIndex(0);
        }
        if (tblTitulares.getModel() instanceof DefaultTableModel) {
            tblTitulares.clearSelection();
            preencherDependentes();
        }
        txtNome.requestFocus();
    }

